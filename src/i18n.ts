export function localeFromPath(pathname: string): Locale {
  return pathname === "/zh" || pathname.startsWith("/zh/") ? "zh" : "en";
}

export function stripLocale(pathname: string): string {
  if (pathname === "/zh") return "/";
  return pathname.startsWith("/zh/") ? pathname.slice(3) || "/" : pathname;
}

export function localizedPath(path: string, locale: Locale): string {
  if (/^(?:https?:|mailto:|tel:|sms:|#)/i.test(path)) return path;
  const [pathAndQuery, hash = ""] = path.split("#", 2);
  const [pathname, query = ""] = pathAndQuery.split("?", 2);
  const bare = stripLocale(pathname || "/");
  const localized =
    locale === "zh" ? (bare === "/" ? "/zh" : `/zh${bare}`) : bare;
  return `${localized}${query ? `?${query}` : ""}${hash ? `#${hash}` : ""}`;
}

export function useLocale() {
  const location = useLocation();
  const locale = localeFromPath(location.pathname);
  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
  }, [locale]);
  return {
    locale,
    isZh: locale === "zh",
    copy: messages[locale],
    path: (value: string) => localizedPath(value, locale),
    switchPath: localizedPath(
      `${location.pathname}${location.search}${location.hash}`,
      locale === "zh" ? "en" : "zh",
    ),
  };
}

export function formatLocalizedPrice(
  value: number | null,
  locale: Locale,
): string {
  if (value === null || !Number.isFinite(value))
    return messages[locale].common.priceRequest;
  return new Intl.NumberFormat(locale === "zh" ? "zh-CN" : "en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(value / 100);
}

export function formatLocalizedMileage(
  value: number | null,
  locale: Locale,
): string {
  if (value === null || !Number.isFinite(value))
    return messages[locale].common.mileageRequest;
  const number = new Intl.NumberFormat(
    locale === "zh" ? "zh-CN" : "en-US",
  ).format(value);
  return locale === "zh" ? `${number} 英里` : `${number} mi`;
}
